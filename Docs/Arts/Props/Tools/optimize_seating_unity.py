import bpy, json, os, bmesh
from mathutils import Vector

src=bpy.context.scene
dst=bpy.data.scenes.new('Seating_AB_Unity_Optimized')
dg=bpy.context.evaluated_depsgraph_get()
roots=[o for o in src.objects if o.parent is None and o.type=='EMPTY']
report=[]
for root in roots:
    nr=root.copy();nr.name=root.name.replace('Detailed','Unity');dst.collection.objects.link(nr)
    nr['source_detail_file']='BBB_Seating_AB_Detailed_Geometry.blend'
    before_v=0;before_t=0;newparts=[]
    for old in root.children_recursive:
        if old.type!='MESH':continue
        ev=old.evaluated_get(dg)
        data=bpy.data.meshes.new_from_object(ev,preserve_all_data_layers=True,depsgraph=dg)
        data.calc_loop_triangles();before_v+=len(data.vertices);before_t+=len(data.loop_triangles)
        ob=bpy.data.objects.new(old.name+'_Game',data);dst.collection.objects.link(ob);ob.parent=nr
        ob.matrix_parent_inverse=old.matrix_parent_inverse.copy();ob.matrix_basis=old.matrix_basis.copy();ob.color=old.color
        n=old.name.lower()
        if 'diamond' in n and len(data.polygons)>1000:ratio=.25
        elif 'deep_apron' in n and len(data.polygons)>1000:ratio=.18
        elif any(k in n for k in ['rolled_arm','continuous_curved']):ratio=.5
        elif 'piped_seam' in n:ratio=.14
        elif any(k in n for k in ['seat','pillow','padded_back','bolster','outer_arm_panel']) and len(data.polygons)>1000:ratio=.065
        elif any(k in n for k in ['nail','stud','button']):ratio=.3
        elif 'petal' in n:ratio=.3
        else:ratio=.45
        ob['source_name']=old.name;ob['simplification_ratio']=ratio
        mod=ob.modifiers.new('Game_Mesh_Reduction','DECIMATE');mod.decimate_type='COLLAPSE';mod.ratio=ratio;mod.use_collapse_triangulate=True
        newparts.append(ob)
    report.append({'asset':nr.name,'before_vertices':before_v,'before_triangles':before_t,'before_parts':len(newparts)})
bpy.context.window.scene=dst
for ob in list(dst.objects):
    if ob.type!='MESH':continue
    bpy.context.view_layer.objects.active=ob
    bpy.ops.object.modifier_apply(modifier='Game_Mesh_Reduction')
    # Remove duplicated poles and zero area faces generated by small spherical decorations.
    bm=bmesh.new();bm.from_mesh(ob.data);bmesh.ops.remove_doubles(bm,verts=list(bm.verts),dist=.000001)
    bmesh.ops.dissolve_degenerate(bm,dist=.0000001,edges=list(bm.edges));bm.to_mesh(ob.data);bm.free();ob.data.update()
# Second pass keeps the large silhouette while reducing repetitive small details.
for ob in list(dst.objects):
    if ob.type!='MESH':continue
    n=ob.get('source_name',ob.name).lower();ratio=None
    if any(k in n for k in ['nail','stud']):ratio=.37
    elif 'button' in n:ratio=.6
    elif 'diamond' in n and 'piped' not in n and n.startswith('sofa_b'):ratio=.68
    elif 'deep_apron' in n and 'piped' not in n:ratio=.45
    elif 'rolled_arm' in n and 'piped' not in n:ratio=.6
    elif 'piped_seam' in n:ratio=.65
    elif 'diamond' in n and n.startswith('bench_a'):ratio=.8
    if ratio is not None:
        bpy.context.view_layer.objects.active=ob
        mod=ob.modifiers.new('Final_Reduction','DECIMATE');mod.decimate_type='COLLAPSE';mod.ratio=ratio;mod.use_collapse_triangulate=True
        bpy.ops.object.modifier_apply(modifier=mod.name)

# Consolidate material roles now; materials and UV layout are a later task.
for entry in report:
    root=bpy.data.objects[entry['asset']];groups={'Woodwork':[],'Upholstery':[],'Metalwork':[]}
    for ob in root.children_recursive:
        if ob.type!='MESH':continue
        c=tuple(round(v,2) for v in ob.color[:3])
        role='Upholstery' if c in ((.68,.65,.59),(.52,.49,.44)) else 'Metalwork' if c==(.53,.50,.43) else 'Woodwork'
        groups[role].append(ob)
    prefix=root.name.replace('_Unity_ROOT','')
    for role,parts in groups.items():
        if not parts:continue
        bpy.ops.object.select_all(action='DESELECT')
        for ob in parts:ob.select_set(True)
        bpy.context.view_layer.objects.active=parts[0]
        if len(parts)>1:bpy.ops.object.join()
        ob=bpy.context.object;ob.name=prefix+'_'+role;ob['material_role']=role
for entry in report:
    r=bpy.data.objects[entry['asset']];parts=[o for o in r.children_recursive if o.type=='MESH'];v=t=0
    for o in parts:o.data.calc_loop_triangles();v+=len(o.data.vertices);t+=len(o.data.loop_triangles)
    entry['vertices']=v;entry['triangles']=t;entry['mesh_parts']=len(parts)
dst['optimization_report']=json.dumps(report)
for a in bpy.context.screen.areas:
    if a.type=='VIEW_3D':
        sh=a.spaces.active.shading;sh.type='SOLID';sh.light='STUDIO';sh.color_type='OBJECT';sh.show_cavity=True
        v=a.spaces.active.region_3d;v.view_location=(0,-.15,.65);v.view_distance=6.6;v.view_rotation=Vector((.25,-1,.65)).to_track_quat('Z','Y')
print(json.dumps(report,indent=2))
